import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch

from cwdprobe.process import run_process
from cwdprobe.workspace import Workspace, validate_root

PROJECT = Path(__file__).resolve().parents[1]


class SafetyTests(unittest.TestCase):
    def setUp(self):
        self.w = Workspace(Path(os.environ["CWDPROBE_TEST_ROOT"]))
        self.cwd = self.w.case("ascii", 1)

    def tearDown(self):
        if self.w.path.exists():
            self.w.cleanup()

    def test_cleanup_locks_nested_ancestor_against_rename(self):
        try:
            from cwdprobe import winfs
        except ImportError:
            winfs = None
        self.assertIsNotNone(winfs, "handle-anchored cleanup is not implemented")
        nested = self.cwd / "nested"
        nested.mkdir()
        (nested / "sample").write_text("owned", encoding="ascii")
        attempted = []
        original = winfs.delete_handle

        def attempt_rename(handle):
            if not attempted:
                attempted.append(True)
                with self.assertRaises(PermissionError):
                    nested.rename(self.cwd / "renamed")
            return original(handle)

        with patch("cwdprobe.winfs.delete_handle", side_effect=attempt_rename):
            self.w.cleanup()
        self.assertTrue(attempted)
        self.assertFalse(self.w.path.exists())

    def test_network_drive_policy_is_fail_closed(self):
        import cwdprobe.workspace as policy
        self.assertTrue(hasattr(policy, "drive_type"), "drive type policy is not implemented")
        with patch("cwdprobe.workspace.drive_type", return_value=4):
            with self.assertRaises(ValueError):
                validate_root(self.cwd)

    def test_hardlink_refusal_preserves_file(self):
        target = self.cwd / "protected"
        target.write_text("keep", encoding="ascii")
        link = self.cwd / "hardlink"
        os.link(target, link)
        try:
            with self.assertRaises(ValueError):
                self.w.cleanup()
            self.assertEqual(target.read_text(), "keep")
            self.assertTrue(link.exists())
        finally:
            link.unlink()

    def test_replaced_run_identity_is_refused(self):
        original = self.w.path
        retained = original.with_name(original.name + "-retained")
        original.rename(retained)
        original.mkdir()
        marker = original / ".cwdprobe-owner"
        marker.write_text(self.w.token, encoding="ascii")
        try:
            with self.assertRaises(ValueError):
                self.w.cleanup()
            self.assertTrue(retained.exists())
            self.assertTrue(marker.exists())
        finally:
            marker.unlink()
            original.rmdir()
            retained.rename(original)

    def test_job_attach_failure_never_runs_user_code(self):
        with patch("cwdprobe.process.Job.attach_and_resume", side_effect=OSError("attach refused")):
            r = run_process([sys.executable, "-c", "open('must-not-exist','w').write('bad')"],
                            self.cwd, 2, 1024, "utf-8")
        self.assertEqual(r["state"], "TOOL_ERROR")
        self.assertFalse((self.cwd / "must-not-exist").exists())

    def test_junction_is_not_followed_or_deleted(self):
        target = self.cwd / "protected"
        target.mkdir()
        (target / "keep").write_text("keep", encoding="ascii")
        nested = self.cwd / "nested"
        nested.mkdir()
        link = nested / "junction"
        # cmd is required only for this fixed test fixture: native mklink /J.
        # Paths are generated by us, contain no shell metacharacters and are quoted.
        p = subprocess.run(["cmd.exe", "/d", "/c", "mklink", "/J", str(link), str(target)],
                           capture_output=True, timeout=10)
        self.assertEqual(p.returncode, 0, p.stderr)
        try:
            with self.assertRaises(ValueError):
                validate_root(link)
            with self.assertRaises(ValueError):
                self.w.cleanup()
            self.assertEqual((target / "keep").read_text(), "keep")
            self.assertTrue(link.exists())
        finally:
            os.rmdir(link)  # remove only the created junction, never recursively

    def test_real_denied_write_is_setup_error(self):
        with tempfile.TemporaryDirectory(prefix="cwdprobe-denied-report-") as reports:
            deny = subprocess.run(["icacls.exe", str(self.cwd), "/deny", "*S-1-1-0:(WD,AD)"],
                                  capture_output=True, timeout=10)
            self.assertEqual(deny.returncode, 0, deny.stderr)
            try:
                p = subprocess.run([sys.executable, "-m", "cwdprobe", "--root", str(self.cwd),
                                    "--report", str(Path(reports) / "denied"), "--demo", "good"],
                                   cwd=PROJECT, capture_output=True, timeout=10)
                self.assertEqual(p.returncode, 2, p.stdout)
                r = json.loads((Path(reports) / "denied/report.json").read_text(encoding="utf-8"))
                self.assertEqual(r["summary"]["status"], "TOOL_ERROR")
                self.assertEqual(r["results"], [])
            finally:
                restore = subprocess.run(["icacls.exe", str(self.cwd), "/remove:d", "*S-1-1-0"],
                                         capture_output=True, timeout=10)
                self.assertEqual(restore.returncode, 0, restore.stderr)

    def test_keyboard_interrupt_releases_job_and_workspace(self):
        # Real runner lifecycle and file cleanup; deterministic in-process SIGINT
        # uses Python's actual KeyboardInterrupt rather than a fake result row.
        from cwdprobe.experiment import run_experiment
        import threading
        import _thread
        timer = threading.Timer(0.5, _thread.interrupt_main)
        timer.start()
        try:
            r = run_experiment([sys.executable, "-c", "import time; time.sleep(30)"], self.cwd)
        finally:
            timer.cancel()
            timer.join()
        self.assertEqual(r["summary"]["status"], "INTERRUPTED")
        self.assertEqual(r["cleanup"]["status"], "PASS")
        self.assertFalse(Path(r["workspace"]).exists())
